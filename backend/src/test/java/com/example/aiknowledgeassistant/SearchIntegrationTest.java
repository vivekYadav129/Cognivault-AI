package com.example.aiknowledgeassistant;

import com.example.aiknowledgeassistant.dto.request.LoginRequest;
import com.example.aiknowledgeassistant.dto.request.RegisterRequest;
import com.example.aiknowledgeassistant.dto.request.SearchRequest;
import com.example.aiknowledgeassistant.repository.DocumentRepository;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.http.MediaType;
import org.springframework.mock.web.MockMultipartFile;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;

import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.multipart;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

@SpringBootTest
@AutoConfigureMockMvc
@ActiveProfiles("dev")
public class SearchIntegrationTest {

    @Autowired
    private MockMvc mockMvc;

    @Autowired
    private ObjectMapper objectMapper;

    @Autowired
    private DocumentRepository documentRepository;

    private String user1Token;
    private String user2Token;
    private Long user1DocId;

    @BeforeEach
    public void setupAndUploadDocument() throws Exception {
        documentRepository.deleteAll();

        // Register User 1
        RegisterRequest user1Req = RegisterRequest.builder()
                .name("Vector User 1")
                .email("vector1@example.com")
                .password("Password123")
                .build();

        MvcResult r1 = mockMvc.perform(post("/api/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(user1Req)))
                .andReturn();

        if (r1.getResponse().getStatus() == 201) {
            user1Token = objectMapper.readTree(r1.getResponse().getContentAsString()).get("token").asText();
        } else {
            LoginRequest login1 = LoginRequest.builder().email("vector1@example.com").password("Password123").build();
            MvcResult l1 = mockMvc.perform(post("/api/auth/login")
                            .contentType(MediaType.APPLICATION_JSON)
                            .content(objectMapper.writeValueAsString(login1)))
                    .andReturn();
            user1Token = objectMapper.readTree(l1.getResponse().getContentAsString()).get("token").asText();
        }

        // Register User 2
        RegisterRequest user2Req = RegisterRequest.builder()
                .name("Vector User 2")
                .email("vector2@example.com")
                .password("Password123")
                .build();

        MvcResult r2 = mockMvc.perform(post("/api/auth/register")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(user2Req)))
                .andReturn();

        if (r2.getResponse().getStatus() == 201) {
            user2Token = objectMapper.readTree(r2.getResponse().getContentAsString()).get("token").asText();
        } else {
            LoginRequest login2 = LoginRequest.builder().email("vector2@example.com").password("Password123").build();
            MvcResult l2 = mockMvc.perform(post("/api/auth/login")
                            .contentType(MediaType.APPLICATION_JSON)
                            .content(objectMapper.writeValueAsString(login2)))
                    .andReturn();
            user2Token = objectMapper.readTree(l2.getResponse().getContentAsString()).get("token").asText();
        }

        // Upload Document for User 1
        String docContent = "PostgreSQL pgvector extension enables vector similarity search in relational databases. " +
                "It allows storing high-dimensional embeddings generated by LLMs and retrieving nearest neighbors using cosine similarity.";

        MockMultipartFile file = new MockMultipartFile(
                "file",
                "pgvector-guide.txt",
                "text/plain",
                docContent.getBytes()
        );

        MvcResult uploadResult = mockMvc.perform(multipart("/api/documents/upload")
                        .file(file)
                        .header("Authorization", "Bearer " + user1Token))
                .andExpect(status().isCreated())
                .andReturn();

        user1DocId = objectMapper.readTree(uploadResult.getResponse().getContentAsString()).get("id").asLong();
    }

    @Test
    public void testVectorSearchReturnsRelevantChunksForAuthenticatedUser() throws Exception {
        SearchRequest searchReq = new SearchRequest("What is pgvector extension?", 5, null);

        mockMvc.perform(post("/api/search")
                        .header("Authorization", "Bearer " + user1Token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(searchReq)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.count").value(1))
                .andExpect(jsonPath("$.results[0].documentId").value(user1DocId))
                .andExpect(jsonPath("$.results[0].content").value(org.hamcrest.Matchers.containsString("pgvector extension")));
    }

    @Test
    public void testUserIsolationInVectorSearch() throws Exception {
        // User 2 performs search -> Should return 0 results because User 2 has no documents uploaded
        SearchRequest searchReq = new SearchRequest("What is pgvector extension?", 5, null);

        mockMvc.perform(post("/api/search")
                        .header("Authorization", "Bearer " + user2Token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(searchReq)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.count").value(0))
                .andExpect(jsonPath("$.results").isEmpty());
    }

    @Test
    public void testInvalidTopKValidation() throws Exception {
        SearchRequest invalidTopKReq = new SearchRequest("Test query", 50, null); // Max allowed topK is 20

        mockMvc.perform(post("/api/search")
                        .header("Authorization", "Bearer " + user1Token)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(objectMapper.writeValueAsString(invalidTopKReq)))
                .andExpect(status().isBadRequest());
    }
}
